# Funções:
# são blocos de código reutilizáveis que executam uma tarefa específica
# ajudam a organizar o código, evitar repetições e facilitar a manutenção do sistema
# Criando uma função:
# 1 - utilizamos a palavra reservada def
# 2 - Nome da função
# 3 - Parênteses ()
# 4 - Dois pontos :
# 5 - Bloco de código **identado**
# Ao criar funções:
# Utilize letras minúsculas
# Use nomes descritivos
# Separe palavras com _

def boas_vindas():
    print("Olá!")
    print("Bem-vindo ao sistema!")

boas_vindas()

