# O que é o PyPI?
# O PyPI (Python Package Index), em https://pypi.org/, é um repositório de pacotes da linguagem Python. 
# Nele, desenvolvedores do mundo inteiro compartilham bibliotecas e ferramentas que podem ser instaladas e utilizadas em projetos Python.
# Até aqui, utilizamos módulos nativos do Python, disponíveis no Python Module Index — aqueles que já vêm embutidos na linguagem. 
# O PyPI vai além: dá acesso a bibliotecas desenvolvidas pela comunidade, que não acompanham a instalação do Python e precisam ser baixadas separadamente.
# Exemplos de uso
# Um desenvolvedor pode transformar uma solução em pacote e publicá-la no PyPI para que outras pessoas a utilizem. Há pacotes para praticamente tudo:
# envio de SMS;
# manipulação de Excel;
# criação de sites;
# automações;
# integração com APIs;
# análise de dados; entre outros.
# Cuidados ao usar bibliotecas da comunidade
# Como os pacotes são desenvolvidos pela comunidade, antes de adotar um deles vale observar:
# manutenção do projeto;
# data da última atualização;
# problemas conhecidos;
# documentação;
# segurança;
# popularidade da biblioteca